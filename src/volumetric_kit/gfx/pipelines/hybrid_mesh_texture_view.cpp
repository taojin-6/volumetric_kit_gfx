// A pyramid's format: the build writes linear light that the hardware
// encodes, the blits decode, average and re-encode, and a draw samples linear
// light back. Rendering, blitting and linear filtering of it are mandatory in
// Vulkan.
constexpr VkFormat kPyramidFormat = VK_FORMAT_R8G8B8A8_SRGB;
constexpr VkFormatFeatureFlags kPyramidFeatures =
    VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT |
    VK_FORMAT_FEATURE_SAMPLED_IMAGE_FILTER_LINEAR_BIT |
    VK_FORMAT_FEATURE_COLOR_ATTACHMENT_BIT | VK_FORMAT_FEATURE_BLIT_SRC_BIT |
    VK_FORMAT_FEATURE_BLIT_DST_BIT;

// The most pixels of the level read across a footprint, less one: a level
// is read where the footprint spans at most this many of its pixels.
constexpr float kMaxSpan = 4.0f;

// image_draw.vert's push block, then texture_view.frag's (std430).
struct ViewPush {
  float target_size[2];  // the render target, in pixels
  float rect_min[2];     // the rectangle's top-left, in target pixels
  float rect_max[2];     // its bottom-right
  float uv_min[2];       // the texture's uv at rect_min
  float uv_max[2];       // at rect_max
  float footprint;       // picture pixels per target pixel
  int32_t level;         // -1, the nearest pixel; 0, the picture; L, L - 1
  uint32_t picture;      // the picture the uv names
};
static_assert(sizeof(ViewPush) == 52, "ViewPush must match the shaders");
static_assert(offsetof(ViewPush, footprint) == 40, "ViewPush layout drift");

// The level a draw of footprint `f` reads over a pyramid of `levels` levels:
// -1 magnified, else the lowest whose pixels bring the footprint within
// kMaxSpan, at most `levels`. A small slack keeps an exact power of two on
// the finer level.
int level_for(float f, uint32_t levels) {
  constexpr float kSlack = 1e-4f;
  if (!(f > 1.0f + kSlack)) {
    return -1;
  }
  const float over = std::ceil(std::log2(f / kMaxSpan) - kSlack);
  return static_cast<int>(std::clamp(over, 0.0f, static_cast<float>(levels)));
}

core::Result<ShaderModule> embedded_module(VkDevice device,
                                           const unsigned char* spv,
                                           std::size_t size) {
  return ShaderModule::create(device, reinterpret_cast<const uint32_t*>(spv),
                              size);
}

