constexpr const char* kSubmit = "DepthCloudPipeline::submit";

// depth_cloud.vert's uniform block (std140): two matrices, then three vec4s.
struct Params {
  glm::mat4 depth_to_clip;
  glm::mat4 depth_to_color;
  uint32_t grid[4];   // depth width, columns, stride, colour width
  uint32_t style[4];  // mode, tint, flags, colour height
  float range[4];     // nearest depth, farthest depth, point size, unused
};
static_assert(sizeof(Params) == 176, "Params must match depth_cloud.vert");
static_assert(offsetof(Params, depth_to_color) == 64, "Params layout drift");
static_assert(offsetof(Params, grid) == 128, "Params layout drift");
static_assert(offsetof(Params, style) == 144, "Params layout drift");
static_assert(offsetof(Params, range) == 160, "Params layout drift");

// Params::style[2].
constexpr uint32_t kHasColor = 1;
constexpr uint32_t kAlphaIsCoverage = 2;

// depth_cloud.vert's bindings in set 0.
constexpr uint32_t kDepthBinding = 0;
constexpr uint32_t kColorBinding = 1;
constexpr uint32_t kParamsBinding = 2;

core::Status draw_error(uint32_t index, const std::string& what) {
  return core::Status::invalid_argument(std::string(kSubmit) + ": draw " +
                                        std::to_string(index) + " " + what);
}

bool finite(const glm::dmat4& m) {
  for (int c = 0; c < 4; ++c) {
    for (int r = 0; r < 4; ++r) {
      if (!std::isfinite(m[c][r])) {
        return false;
      }
    }
  }
  return true;
}

// What a draw's image needs of its camera, buffer and offset; empty when it
// passes. `what` is "depth" or "colour".
std::string check_image(const core::Buffer& buffer, VkDeviceSize offset,
                        const camera::PinholeCamera& cam,
                        const VkPhysicalDeviceLimits& limits,
                        const char* what) {
  const std::string name = what;
  if ((buffer.usage() & VK_BUFFER_USAGE_STORAGE_BUFFER_BIT) == 0) {
    return "has a " + name + " buffer without STORAGE_BUFFER usage";
  }
  if (cam.width == 0 || cam.height == 0) {
    return "has a " + name + " camera of zero size";
  }
  if (!(std::isfinite(cam.fx) && cam.fx > 0.0f && std::isfinite(cam.fy) &&
        cam.fy > 0.0f && std::isfinite(cam.cx) && std::isfinite(cam.cy))) {
    return "has a " + name +
           " camera whose focal lengths are not positive and finite or "
           "whose principal point is not finite";
  }
  // 64-bit: a 32-bit size squared cannot wrap.
  const uint64_t bytes = uint64_t{cam.width} * cam.height * 4;
  if (bytes > limits.maxStorageBufferRange) {
    return "has a " + name + " image larger than maxStorageBufferRange";
  }
  if (offset % limits.minStorageBufferOffsetAlignment != 0) {
    return "has a " + name +
           " offset that is not a multiple of "
           "minStorageBufferOffsetAlignment";
  }
  if (offset > buffer.size() || bytes > buffer.size() - offset) {
    return "has a " + name + " image beyond its buffer";
  }
  return {};
}

// The inverse of `cam`'s intrinsics as a 4x4: (u z, v z, z, 1) to the
// camera's point. glm is column-major: m[column][row].
glm::dmat4 unproject(const camera::PinholeCamera& cam) {
  glm::dmat4 m(1.0);
  m[0][0] = 1.0 / cam.fx;
  m[1][1] = 1.0 / cam.fy;
  m[2][0] = -double{cam.cx} / cam.fx;
  m[2][1] = -double{cam.cy} / cam.fy;
  return m;
}

// `cam`'s intrinsics as a 4x4: a camera point (x, y, z, 1) to
// (fx x + cx z, fy y + cy z, z, 1), pixel (x / z, y / z).
glm::dmat4 project(const camera::PinholeCamera& cam) {
  glm::dmat4 m(1.0);
  m[0][0] = cam.fx;
  m[1][1] = cam.fy;
  m[2][0] = cam.cx;
  m[2][1] = cam.cy;
  return m;
}

// Checks `draw` and, when it passes, fills `params` for it. Matrices fold in
// double, so a large pose loses nothing before the one rounding to float.
core::Status prepare(uint32_t index, const DepthCloudDraw& draw,
                     const VkPhysicalDeviceLimits& limits,
                     const detail::PointDrawLimits& points, Params& params) {
  const DepthSource& depth = draw.depth;
  const ColorSource& color = draw.color;
  if (depth.buffer == nullptr || !depth.buffer->valid()) {
    return draw_error(index, "has no depth buffer");
  }
  std::string bad =
      check_image(*depth.buffer, depth.offset, depth.camera, limits, "depth");
  if (!bad.empty()) {
    return draw_error(index, bad);
  }
  const bool has_color = color.buffer != nullptr;
  if (has_color) {
    if (!color.buffer->valid()) {
      return draw_error(index, "has an empty colour buffer");
    }
    bad = check_image(*color.buffer, color.offset, color.camera, limits,
                      "colour");
    if (!bad.empty()) {
      return draw_error(index, bad);
    }
  }
  if (!(std::isfinite(depth.min_depth) && depth.min_depth >= 0.0f &&
        std::isfinite(depth.max_depth) && depth.max_depth >= 0.0f)) {
    return draw_error(index,
                      "has a depth bound that is negative or not finite");
  }
  if (depth.max_depth > 0.0f && depth.min_depth > depth.max_depth) {
    return draw_error(index, "has min_depth above max_depth");
  }
  if (draw.mode != CloudColor::Solid && draw.mode != CloudColor::TintedLuma &&
      draw.mode != CloudColor::True) {
    return draw_error(index, "has an unknown colour mode");
  }
  if (draw.stride == 0) {
    return draw_error(index, "has a zero stride");
  }
  if (!(std::isfinite(draw.point_size) && draw.point_size > 0.0f)) {
    return draw_error(index,
                      "has a point size that is not positive and finite");
  }
  const VkRect2D& rect = draw.viewport;
  if (rect.extent.width != 0 && rect.extent.height != 0 &&
      !points.viewport_fits(rect)) {
    return draw_error(index,
                      "has a viewport beyond the device's "
                      "maxViewportDimensions or viewportBoundsRange");
  }

  const glm::dmat4 view_proj(draw.view_proj);
  const glm::dmat4 depth_to_world(depth.to_world);
  if (!finite(view_proj) || !finite(depth_to_world)) {
    return draw_error(index, "has a view or depth pose that is not finite");
  }
  const glm::dmat4 depth_cam = depth_to_world * unproject(depth.camera);
  glm::dmat4 to_color(0.0);
  if (has_color) {
    const glm::dmat4 color_to_world(color.to_world);
    if (!finite(color_to_world) || glm::determinant(color_to_world) == 0.0) {
      return draw_error(index, "has a colour pose that cannot be inverted");
    }
    to_color = project(color.camera) * glm::inverse(color_to_world) * depth_cam;
    if (!finite(to_color)) {
      return draw_error(index, "has a colour pose that cannot be inverted");
    }
  }

  const camera::PinholeCamera& d = depth.camera;
  params.depth_to_clip = glm::mat4(view_proj * depth_cam);
  params.depth_to_color = glm::mat4(to_color);
  params.grid[0] = d.width;
  params.grid[1] = (d.width + draw.stride - 1) / draw.stride;
  params.grid[2] = draw.stride;
  params.grid[3] = has_color ? color.camera.width : 0;
  params.style[0] = static_cast<uint32_t>(draw.mode);
  params.style[1] = draw.tint;
  params.style[2] =
      (has_color ? kHasColor : 0) |
      (has_color && color.alpha_is_coverage ? kAlphaIsCoverage : 0);
  params.style[3] = has_color ? color.camera.height : 0;
  // No bound is the largest finite depth, so an infinite one is gated too.
  params.range[0] = depth.min_depth;
  params.range[1] = depth.max_depth > 0.0f ? depth.max_depth
                                           : std::numeric_limits<float>::max();
  params.range[2] = points.clamp(draw.point_size);
  params.range[3] = 0.0f;
  return core::Status{};
}

// The vertex count of `draw`: its columns times its rows.
uint32_t vertex_count(const DepthCloudDraw& draw) {
  const uint32_t columns =
      (draw.depth.camera.width + draw.stride - 1) / draw.stride;
  const uint32_t rows =
      (draw.depth.camera.height + draw.stride - 1) / draw.stride;
  // prepare() bounded width * height by maxStorageBufferRange / 4.
  return columns * rows;
}

